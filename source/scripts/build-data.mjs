function normalizePort(port) {
  const supplied = typeof port === 'string' ? { name: port } : port;
  const rawName = supplied.name.split(',')[0].trim();
  const normalizedName = aliases[supplied.name] || aliases[rawName] || (portLocations[supplied.name] ? supplied.name : rawName);
  const coordinates = portLocations[normalizedName];
  if (!coordinates && !(Number.isFinite(supplied.lat) && Number.isFinite(supplied.lon))) {
    throw new Error(`Unknown port: ${supplied.name}`);
  }
  return {
    name: normalizedName,
    lat: supplied.lat ?? coordinates[0],
    lon: supplied.lon ?? coordinates[1],
    country: supplied.country ?? coordinates[2],
  };
}

