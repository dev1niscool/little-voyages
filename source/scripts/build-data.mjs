function schematicRoute(ports) {
  if (!ports.length) return [];
  const coordinates = [[ports[0].lon, ports[0].lat]];
  for (let i = 1; i < ports.length; i++) {
    const from = ports[i - 1].name;
    const to = ports[i].name;
    const forward = seaLegs.find(([a, b]) => a === from && b === to);
    const reverse = seaLegs.find(([a, b]) => a === to && b === from);
    if (forward) coordinates.push(...forward[2]);
    else if (reverse) coordinates.push(...reverse[2].toReversed());
    coordinates.push([ports[i].lon, ports[i].lat]);
  }
  return coordinates;
}

